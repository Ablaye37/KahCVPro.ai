def ameliorer_cv(texte):
    """
    Améliore le texte d'un CV.
    Version de base avant l'intégration d'une vraie IA.
    """

    resultat = (
        "Profil professionnel amélioré :\n\n"
        + texte
        + "\n\n"
        "Professionnel motivé, capable de travailler en équipe "
        "et de résoudre des problèmes efficacement."
    )

    return resultat
